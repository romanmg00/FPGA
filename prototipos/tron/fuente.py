# Letras con algo arriba (fila 0 de la celda).
_ARRIBA = {
    "Á": ("A", "...#."), "É": ("E", "...#."), "Í": ("I", "...#."),
    "Ó": ("O", "...#."), "Ú": ("U", "...#."), "Ñ": ("N", ".##.#"),
}


def _celda(arriba, filas):
    """5x7 (+ fila de arriba) -> 8 filas de 8 columnas, letra en las columnas 1-5."""
    return tuple("." + f + ".." for f in (arriba,) + tuple(filas))


FUENTE = {c: _celda(".....", f) for c, f in _BASE.items()}
FUENTE.update({c: _celda(marca, _BASE[base]) for c, (base, marca) in _ARRIBA.items()})


def pixeles(texto):
    """(columna, fila) encendidos de un texto en mayúsculas, sin ampliar."""
    for k, ch in enumerate(texto):
        for fy, fila in enumerate(FUENTE[ch]):
            for fx, p in enumerate(fila):
                if p == "#":
                    yield k * ANCHO_LETRA + fx, fy
