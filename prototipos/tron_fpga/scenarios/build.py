def s05_head_on_swap():
    d = Driver()
    d.start()
    d.until(lambda g: g.phase != PLAY)
    return d, "Head-on Crash by swapping Cells", [
        "Default starts, no Turns: at Step 20 P1 targets P2's head and P2 targets P1's."]


def s06_reversal_ignored():
    d = Driver()
    d.start()
    d.step(p1=LEFT, p2=RIGHT)                        # both reversals: ignored
    d.step(p1=UP)
    d.step(p1=DOWN)                                  # reversal of UP: ignored
    d.step(p1=RIGHT)
    d.step(p2=LEFT)                                  # same Heading: ignored
    d.until(lambda g: g.phase != PLAY)
    return d, "180 degree input ignored", [
        "P1 LEFT and P2 RIGHT (reversals), P1 DOWN while heading UP and P2 LEFT while",
        "heading LEFT change nothing; P1's UP and RIGHT do. P2 later runs into P1's Trail."]


def s07_two_inputs():
    d = Driver()
    d.start()
    # Two requests in one Step period, in separate ticks: the last valid one wins
    d.tick("btn:U")
    d.tick("btn:D")
    d.until(lambda g: g.step_count == 1)
    d.step()
    # RIGHT, then UP, a reversal of the current Heading DOWN: the Pending RIGHT stays
    d.tick("btn:R")
    d.tick("btn:U")
    d.until(lambda g: g.step_count == 3)
    # A tie in one button sample: UP > RIGHT > DOWN > LEFT among valid requests
    d.tick("btn:U+D")
    d.until(lambda g: g.step_count == 4)
    d.until(lambda g: g.phase != PLAY)
    return d, "Two inputs between Steps", [
        "P1: UP then DOWN before Step 1 (DOWN wins); RIGHT then UP while heading DOWN",
        "(RIGHT stays: UP is a reversal); UP+DOWN in one sample while heading RIGHT (UP)."]


def _respawn_on_occupied(game, start_index):
    trail_or_head = set(range(2, 6))
    for slot, p in game.ctrl.placements[start_index:]:
        if trail_or_head & set(p.rejected):
            return True
    return False


def s08_reward_respawn():
    for seed in range(1, 400):
        rng = random.Random(seed)
        d = Driver({"seed": 0x1000 + seed})
        d.start()
        g = d.game
        initial = len(g.ctrl.placements)
        while g.phase == PLAY:
            d.step(bot_choice(g, 0, True, rng), bot_choice(g, 1, False, rng))
            if _respawn_on_occupied(g, initial):
                d.until(lambda g: g.phase != PLAY)
                return d, "Reward collected and respawned onto an occupied Cell", [
                    "P1 chases Rewards. A respawn's LFSR candidate lands on a Trail or head",
                    "Cell, is rejected, and the Reward goes to a later EMPTY candidate."]
    raise RuntimeError("s08: no run found")


def _to_nine(d, rng, goal):
    """Both bots collect only Rewards that keep them below the goal, until
    both have goal - 1 Points. False if a Crash or a stall spoils the run."""
    g = d.game
    for _ in range(4000):
        if g.phase != PLAY:
            return False
        if g.points == [goal - 1] * 2:
            return True
        turns = []
        for i in (0, 1):
            ok = [c for s_, c in enumerate(g.reward_cells)
                  if c is not None and g.points[i] + g.rules.reward_values[s_] < goal]
            turns.append(bot_choice(g, i, bool(ok), rng, targets=ok))
        d.step(*turns)
    return False


def _finish_together(d):
    """Steer both Bikes onto two different Rewards in the same Step."""
    g = d.game
    cells = [c for c in g.reward_cells if c is not None]
    pairs = []
    for a in cells:
        for b in cells:
            if a == b or (sum(a) - sum(b)) % 2 == 0:
                continue                      # equal path lengths need opposite cell colours
            others = set(cells) - {a, b}
            da = _head_distance(g, 0, a, others)
            db = _head_distance(g, 1, b, others)
            if da and db and (da - db) % 2 == 0:
                pairs.append((max(da, db), a, b))
    if not pairs:
        return False
    length, a, b = min(pairs)
    length += 4                               # room for detours
    for left in range(length, 0, -1):
        if g.phase != PLAY:
            break
        d.step(bot_choice(g, 0, True, random.Random(0), targets=[a], budget=left),
               bot_choice(g, 1, True, random.Random(1), targets=[b], budget=left))
    return g.phase == MATCH_OVER and min(g.points) >= g.goal and not any(g.crashed)


def s09_goal():
    for seed in range(1, 200):
        rng = random.Random(seed)
        d = Driver({"seed": 0x2000 + seed})
        d.start()
        if not (_to_nine(d, rng, d.game.goal) and _finish_together(d)):
            continue
        g = d.game
        first = list(g.points)
        d.tick("sw:0x4000")                          # goal 20 from the next Match
        for _ in range(6):                           # until a Match ends in an overshoot
            bot_match(d, rng, chase=(True, True))
            if g.goal == 20 and max(g.points) > g.goal:
                return d, "Points Goal reached and exceeded, with a simultaneous finish", [
                    f"Match 1 (goal 10): both reach the goal in the same Step, {first};",
                    "higher final Points wins (a Draw if equal).",
                    f"Later Matches use goal 20 (SW15:14 = 01); the last is won by overshooting "
                    f"it: {g.points}."]
    raise RuntimeError("s09: no run found")


def s10_both_last_life():
    d = Driver()
    for _ in range(3):
        d.start()
        d.until(lambda g: g.phase != PLAY)
        d.round_over()
    return d, "Both Bikes Crash on their last Life", [
        "Three swap Head-ons from the default starts; the third costs both their last Life.",
        "Equal Points make it a Draw."]


def s11_new_match():
    d, _, _ = s10_both_last_life()
    d.tick("sw:0x8000")                              # goal 30 for the next Match
    d.tick()
    d.start(via="uart")
    d.step(p1=UP, p2=DOWN)
    d.until(lambda g: g.phase != PLAY)
    return d, "New Match after the Match ends", [
        "After scenario 10's Draw, SW15:14 = 10 and a UART Start (0x20) begin a new Match",
        "with goal 30, three Lives and zero Points."]


def s12_long_random():
    rng = random.Random(12)
    d = Driver({"fixed_seed": 1})
    while d.t < 20000:
        ev = []
        if rng.random() < 0.12:
            ev.append(f"btn:{rng.choice('UDLR')}")
        if rng.random() < 0.12:
            ev.append(f"uart:{rng.choice('wasdWASD')}")
        if rng.random() < 0.03:
            ev.append("btn:C")
        if rng.random() < 0.002:
            ev.append(f"sw:{rng.choice((0, 1, 0x4000, 0xC000))}")
        d.tick(*ev)
    d.tick("sw:0")
    return d, "Long random game", [
        "20,000 ticks of random P1 buttons, P2 UART bytes, Starts, Pause and goal switches."]


SCENARIOS = (
    ("01-walls", s01_walls), ("02-own-trail", s02_own_trail),
    ("03-other-trail", s03_other_trail), ("04-head-on-same-cell", s04_head_on_same_cell),
    ("05-head-on-swap", s05_head_on_swap), ("06-reversal-ignored", s06_reversal_ignored),
    ("07-two-inputs", s07_two_inputs), ("08-reward-respawn", s08_reward_respawn),
    ("09-goal", s09_goal), ("10-both-last-life", s10_both_last_life),
    ("11-new-match", s11_new_match), ("12-long-random", s12_long_random),
)


def build(names=None):
    for name, fn in SCENARIOS:
        if names and name not in names:
            continue
        d, title, notes = fn()
        text = d.scenario_text(title, notes)
        replay = run(parse(text))
        if replay != d.log:
            raise RuntimeError(f"{name}: replaying the file does not reproduce the driver's log")
        with open(os.path.join(HERE, name + ".txt"), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        with open(os.path.join(HERE, name + ".log"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(replay) + "\n")
        print(f"{name}: {d.t} ticks, {len(replay)} log lines")


if __name__ == "__main__":
    import sys
    build(sys.argv[1:])
